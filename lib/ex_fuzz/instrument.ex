defmodule ExFuzz.Instrument do
  @moduledoc false

  # Inserts coverage probes into a module's abstract code.

  @probe_module ExFuzz.Engine
  @probe_function :hit

  @typedoc "An instrumented module, ready to load: name, original object-code path, binary."
  @type compiled :: {module(), charlist(), binary()}

  @doc "Instrument `modules` with probes."
  @spec instrument([module()]) ::
          {:ok, %{binaries: [compiled()], probes: non_neg_integer()}} | {:error, term()}
  def instrument(modules) do
    result =
      Enum.reduce_while(modules, {:ok, [], 0}, fn module, {:ok, compiled, id} ->
        case instrument_module(module, id) do
          {:ok, binary, next_id} -> {:cont, {:ok, [binary | compiled], next_id}}
          {:error, _} = error -> {:halt, error}
        end
      end)

    case result do
      {:ok, compiled, probes} -> {:ok, %{binaries: Enum.reverse(compiled), probes: probes}}
      {:error, _} = error -> error
    end
  end

  @doc "Hot-load instrumented modules, replacing the running code."
  @spec load([compiled()]) :: :ok | {:error, {module(), term()}}
  def load(compiled) do
    Enum.reduce_while(compiled, :ok, fn {module, filename, binary}, :ok ->
      :code.purge(module)

      case :code.load_binary(module, filename, binary) do
        {:module, ^module} -> {:cont, :ok}
        {:error, reason} -> {:halt, {:error, {module, reason}}}
      end
    end)
  end

  defp instrument_module(module, first_id) do
    with {:ok, beam, filename} <- object_code(module),
         {:ok, forms} <- abstract_code(module, beam),
         {forms, next_id} = instrument_forms(forms, first_id),
         {:ok, binary} <- compile(module, forms, preserved_options(beam)) do
      {:ok, {module, filename, binary}, next_id}
    end
  end

  defp object_code(module) do
    case :code.get_object_code(module) do
      {^module, beam, filename} -> {:ok, beam, filename}
      :error -> {:error, {:no_object_code, module}}
    end
  end

  defp abstract_code(module, beam) do
    with {:ok, {^module, [debug_info: {:debug_info_v1, backend, data}]}} when data != :none <-
           :beam_lib.chunks(beam, [:debug_info]),
         {:ok, forms} <- backend.debug_info(:erlang_v1, module, data, []) do
      {:ok, forms}
    else
      _ -> {:error, {:no_debug_info, module}}
    end
  end

  defp compile(module, forms, options) do
    case :compile.forms(forms, [:binary, :return_errors, :no_spawn_compiler_process | options]) do
      {:ok, ^module, binary} -> {:ok, binary}
      {:error, errors, _warnings} -> {:error, {:compile_failed, module, errors}}
    end
  end

  # Same filter as OTP's `cover`, which also recompiles from debug info.
  defp preserved_options(beam) do
    case :beam_lib.chunks(beam, [:compile_info]) do
      {:ok, {_, [compile_info: info]}} ->
        info |> Keyword.get(:options, []) |> Enum.filter(&preserve?/1)

      _ ->
        []
    end
  end

  defp preserve?(option) when option in [:export_all, :tuple_calls], do: true
  defp preserve?({:feature, _, setting}) when setting in [:enable, :disable], do: true
  defp preserve?(_), do: false

  # Insert a probe into every clause of every function in `forms`, numbering them from
  # `first_id`. Returns the rewritten forms and the next unused id.
  defp instrument_forms(forms, first_id) do
    Enum.map_reduce(forms, first_id, fn
      # Generated by Elixir in every module and called often by the runtime: probing it is noise.
      {:function, _, :__info__, 1, _} = form, id ->
        {form, id}

      {:function, anno, name, arity, clauses}, id ->
        {clauses, next_id} = walk(clauses, id)
        {{:function, anno, name, arity, clauses}, next_id}

      form, id ->
        {form, id}
    end)
  end

  defp walk({:clause, anno, patterns, guards, body}, id) do
    {body, next_id} = walk(body, id + 1)
    {{:clause, anno, patterns, guards, [probe(anno, id) | body]}, next_id}
  end

  defp walk(tuple, id) when is_tuple(tuple) do
    {elements, next_id} = tuple |> Tuple.to_list() |> walk(id)
    {List.to_tuple(elements), next_id}
  end

  defp walk(list, id) when is_list(list), do: Enum.map_reduce(list, id, &walk/2)
  defp walk(other, id), do: {other, id}

  defp probe(anno, id) do
    {:call, anno, {:remote, anno, {:atom, anno, @probe_module}, {:atom, anno, @probe_function}},
     [{:integer, anno, id}]}
  end
end
